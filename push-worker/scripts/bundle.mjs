#!/usr/bin/env node
/**
 * Builds dist/worker.js: src/webpush.js and src/index.js joined into ONE ES
 * module, for pasting into the Cloudflare dashboard editor. (Deploying with
 * wrangler doesn't need this; wrangler bundles src/ itself.)
 *
 * Zero dependencies. The sources are written so plain concatenation works:
 * index.js imports only from ./webpush.js, webpush.js imports nothing, and
 * the two files share no top-level names. So the build just drops that one
 * import and the `export` keywords in webpush.js, leaving index.js's
 * `export default` as the bundle's only export.
 *
 * Usage: node scripts/bundle.mjs   (or: npm run bundle)
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT_FILE = join(ROOT, 'dist', 'worker.js');

const IMPORT_WEBPUSH = /^import\s*\{[^}]*\}\s*from\s*['"]\.\/webpush\.js['"];?[ \t]*\r?\n/m;
const EXPORT_KEYWORD = /^export (?=(?:async\s+)?function\b|const\b|let\b|class\b)/gm;

/** Returns the bundled source. Throws if the sources no longer fit the simple scheme above. */
export function bundle() {
  const read = (f) => readFileSync(join(ROOT, 'src', f), 'utf8');
  const helpers = read('webpush.js').replace(EXPORT_KEYWORD, '');
  const main = read('index.js');
  if (!IMPORT_WEBPUSH.test(main)) throw new Error('bundle: index.js no longer imports from ./webpush.js as expected');
  const entry = main.replace(IMPORT_WEBPUSH, '');

  if (/^\s*(import|export)\b/m.test(helpers)) throw new Error('bundle: webpush.js has an import/export the bundler cannot inline');
  if (/^\s*import\b/m.test(entry)) throw new Error('bundle: index.js has an import the bundler cannot inline');
  if ((entry.match(/^export\b/gm) || []).length !== 1 || !/^export default\b/m.test(entry)) {
    throw new Error('bundle: index.js must have exactly one export, the default one');
  }

  return [
    '// vehicles-push: GENERATED by push-worker/scripts/bundle.mjs from push-worker/src/. Do not edit;',
    '// change src/ and run `npm run bundle` again. Paste this whole file into the Cloudflare dashboard.',
    '',
    '// ======== src/webpush.js ========',
    helpers.trim(),
    '',
    '// ======== src/index.js ========',
    entry.trim(),
    '',
  ].join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const code = bundle();
  mkdirSync(dirname(OUT_FILE), { recursive: true });
  writeFileSync(OUT_FILE, code);
  console.log('Wrote ' + OUT_FILE + ' (' + Buffer.byteLength(code) + ' bytes)');
}
